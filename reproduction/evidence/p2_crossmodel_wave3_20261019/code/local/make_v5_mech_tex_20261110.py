"""LaTeX table bodies of tab:self_mech_questions and tab:self_mechanism with MiMo-V2.6-Distill-Qwen-9B as the fifth readout (11-10, user:
"four models and five readouts"), from stats/v5_mechanism.json (make_v5_mechanism_20261110.py) and, for the game columns of the four
other readouts, stats/v4_mech_ext.json, with the cell formats of make_v4_mech_tex_1028.py (functions copied unchanged). The MiMo
game cells are "--": its unedited game does not separate the sources, so the edit is not tested there. The other tables
(tab:self_game, tab:self_exchange, positions, windows) keep the four readouts and stay as generated by make_v4_mech_tex_1028.py.
Output stats/v5_mech_tex_{en,zh}.tex, blocks between "%% <label>" and "%% end".
usage: make_v5_mech_tex_20261110.py ARCHIVE"""
import json
import sys
from pathlib import Path

A = Path(sys.argv[1])
R = json.load(open(A / 'stats' / 'v5_mechanism.json', encoding='utf-8'))['results']
E = json.load(open(A / 'stats' / 'v4_mech_ext.json', encoding='utf-8'))
RO = ['qwen_sp', 'qwen_th', 'oss_th', 'oss120_th', 'mimo_th']
L = {'en': {'own': 'own', 'User': 'User', 'System': 'System', 'unedited': 'unedited', 'random': 'random', 'k64': '64 dims',
            'ro': {'qwen_sp': 'Qwen3.8-27B, no thinking', 'qwen_th': 'Qwen3.8-27B, thinking', 'oss_th': 'gpt-oss-20b, thinking',
                   'oss120_th': 'gpt-oss-120b, thinking', 'mimo_th': 'MiMo-V2.6-Distill-9B, default call'}},
     'zh': {'own': '自己', 'User': 'User', 'System': 'System', 'unedited': '未编辑', 'random': '随机', 'k64': '64 维',
            'ro': {'qwen_sp': 'Qwen3.8-27B，不思考', 'qwen_th': 'Qwen3.8-27B，思考', 'oss_th': 'gpt-oss-20b，思考',
                   'oss120_th': 'gpt-oss-120b，思考', 'mimo_th': 'MiMo-V2.6-Distill-9B，默认调用'}}}


def sg(x, d=2):
    s = f'{x:+.{d}f}'
    if s in ('+0.00', '-0.00', '+0.000', '-0.000'):
        return f'\\({abs(x):.{d}f}\\)'
    return f'\\({s}\\)'


def ch(s, ci=True, d=2):
    if s is None or 'diff' not in s:
        return '--'
    d_ = 3 if abs(s['diff']) < 0.005 and s['diff'] != 0 else d
    t = sg(s['diff'], d_)
    if ci:
        t += f" [{sg(s['diff_ci'][0], d_)}, {sg(s['diff_ci'][1], d_)}]"
    return t


def val(s):
    if s is None:
        return '--'
    t = f"{s['stat']:.2f}"
    if s.get('finished', s['n']) != s['n']:
        t += f" ({s['finished']}/{s['n']})"
    return t


def acc_range(runs, conds=None):
    xs = [s['accuracy'] for c, s in runs.items() if 'accuracy' in s and (conds is None or c in conds)]
    if not xs:
        return '--'
    lo, hi = min(xs), max(xs)
    return f'{lo:.2f}' if f'{lo:.2f}' == f'{hi:.2f}' else f'{lo:.2f}--{hi:.2f}'


def gch(s, ci=True):
    if s is None or 'diff' not in s:
        return '--'
    t = sg(s['diff'])
    if ci:
        t += f" [{sg(s['diff_ci'][0])}, {sg(s['diff_ci'][1])}]"
    return t


def build(lang):
    t = L[lang]
    out = ['%% tab:self_mech_questions']
    for ro in RO:
        a = R[ro].get('all', {})
        g = E['games'].get(ro, {}).get('main', {})
        out.append(f"{t['ro'][ro]} & {ch(a.get('swU8_A'), False)} & {ch(a.get('swA8_U'), False)} & {gch(g.get('swU8_A'), False)} & "
                   f"{gch(g.get('swA8_U'), False)} & {acc_range(R[ro].get('all_content', {}))} & {acc_range(R[ro].get('all_arith', {}))} \\\\")
    out += ['%% end', '%% tab:self_mechanism']
    rows = [(f"{t['own']}, {t['unedited']}", 'all', 'base_A', 'v'), (f"{t['own']} \\(\\leftarrow\\) {t['User']}", 'all', 'swU8_A', 'c'),
            (f"{t['own']} \\(\\leftarrow\\) {t['System']}", 'all', 'swS8_A', 'c'),
            (f"{t['own']} \\(\\leftarrow\\) {t['User']}, {t['random']}", 'all', 'rswU8_A', 'c'),
            (f"{t['own']} \\(\\leftarrow\\) {t['User']}, {t['k64']}", 'all_k64', 'swU64_A', 'c'),
            (f"{t['own']} \\(\\leftarrow\\) {t['User']}, {t['k64']}, {t['random']}", 'all_k64', 'rswU64_A', 'c'), None,
            (f"{t['User']}, {t['unedited']}", 'all', 'base_U', 'v'), (f"{t['User']} \\(\\leftarrow\\) {t['own']}", 'all', 'swA8_U', 'c'),
            (f"{t['User']} \\(\\leftarrow\\) {t['own']}, {t['random']}", 'all', 'rswA8_U', 'c'),
            (f"{t['User']} \\(\\leftarrow\\) {t['own']}, {t['k64']}", 'all_k64', 'swA64_U', 'c'),
            (f"{t['User']} \\(\\leftarrow\\) {t['own']}, {t['k64']}, {t['random']}", 'all_k64', 'rswA64_U', 'c'), None,
            (f"{t['System']}, {t['unedited']}", 'all', 'base_S', 'v'), (f"{t['System']} \\(\\leftarrow\\) {t['own']}", 'all', 'swA8_S', 'c')]
    for r in rows:
        if r is None:
            out.append('\\midrule')
            continue
        lab, run, c, kind = r
        out.append(f'{lab} & ' + ' & '.join((val if kind == 'v' else ch)(R[ro].get(run, {}).get(c)) for ro in RO) + ' \\\\')
    out.append('%% end')
    return '\n'.join(out) + '\n'


for lang in ('en', 'zh'):
    (A / 'stats' / f'v5_mech_tex_{lang}.tex').write_text(build(lang), encoding='utf-8', newline='\n')
print(build('en'))
